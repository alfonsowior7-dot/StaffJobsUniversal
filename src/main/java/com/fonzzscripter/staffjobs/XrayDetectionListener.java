package com.fonzzscripter.staffjobs;

import org.bukkit.GameMode;
import org.bukkit.Material;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.block.BlockBreakEvent;
import org.bukkit.inventory.ItemStack;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.UUID;

/**
 * Detects unusually large amounts of configured rare materials produced
 * by mining blocks during a rolling time window. Alerts are investigative
 * signals, never automatic proof of cheating.
 */
public final class XrayDetectionListener implements Listener {
    private final StaffJobsPlugin plugin;
    private final Map<UUID, Map<Material, Deque<Mining>>> mining = new HashMap<>();
    private final Map<String, Long> lastAlert = new HashMap<>();

    public XrayDetectionListener(StaffJobsPlugin plugin) {
        this.plugin = plugin;
    }

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onOreMined(BlockBreakEvent event) {
        if (!plugin.getConfig().getBoolean("settings.xray-detection.enabled", true)) return;

        Player player = event.getPlayer();
        if (player.getGameMode() == GameMode.CREATIVE || player.getGameMode() == GameMode.SPECTATOR) return;

        // Read the drops generated by this mined block and held tool.
        // This counts the mining event itself, not the later item pickup.
        for (ItemStack drop : event.getBlock().getDrops(player.getInventory().getItemInMainHand(), player)) {
            Material material = drop.getType();
            String base = "settings.xray-detection.materials." + material.name();
            if (!plugin.getConfig().getBoolean(base + ".enabled", false)) continue;

            int threshold = Math.max(1, plugin.getConfig().getInt(base + ".threshold", Integer.MAX_VALUE));
            long windowMs = Math.max(1L, plugin.getConfig().getLong(
                    "settings.xray-detection.time-window-seconds", 60L)) * 1000L;
            long now = System.currentTimeMillis();

            Map<Material, Deque<Mining>> byMaterial =
                    mining.computeIfAbsent(player.getUniqueId(), key -> new HashMap<>());
            Deque<Mining> history = byMaterial.computeIfAbsent(material, key -> new ArrayDeque<>());
            history.addLast(new Mining(now, drop.getAmount()));

            while (!history.isEmpty() && now - history.peekFirst().time > windowMs) {
                history.removeFirst();
            }

            int total = 0;
            for (Mining record : history) total += record.amount;
            if (total < threshold) continue;

            String alertKey = player.getUniqueId() + ":" + material.name();
            long cooldown = Math.max(0L, plugin.getConfig().getLong(
                    "settings.xray-detection.alert-cooldown-seconds", 60L)) * 1000L;
            long previous = lastAlert.getOrDefault(alertKey, 0L);
            if (cooldown > 0L && now - previous < cooldown) continue;
            lastAlert.put(alertKey, now);

            if (!plugin.getConfig().getBoolean("settings.xray-detection.notify-staff", true)) continue;
            String message = "§8[§cSTAFFJOBS X-Ray§8] §e" + player.getName()
                    + " §7mined drops totaling §c" + total + " "
                    + material.name().toLowerCase(Locale.ROOT)
                    + " §7within §f" + (windowMs / 1000L)
                    + "s§7. §cInvestigate manually; this is not proof of cheating.";
            for (Player staff : plugin.getServer().getOnlinePlayers()) {
                if (staff.hasPermission("staffjobs.xray.alert")
                        || staff.hasPermission("staffjobs.protect.bypass")) {
                    staff.sendMessage(message);
                }
            }
        }
    }

    private static final class Mining {
        private final long time;
        private final int amount;

        private Mining(long time, int amount) {
            this.time = time;
            this.amount = amount;
        }
    }
}
